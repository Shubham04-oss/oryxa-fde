#!/usr/bin/env bash
# Copies the platform base (core, authn, authz, events) into vendor/oryxa-platform, unchanged, at one commit.
# Usage: scripts/sync-platform.sh [<commit-or-branch>]   (default: main)
# Never edit vendor/oryxa-platform by hand: change the platform, then run this again.
set -euo pipefail

REV="${1:-main}"
REPO="Shubham04-oss/oryxa-platform"
HERE="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$HERE/vendor/oryxa-platform"
CRATES=(oryxa-core oryxa-authn oryxa-authz oryxa-spicedb-proto oryxa-events)
# Proto trees the crates' build scripts read. The connector contract is not needed.
PROTO=(authzed buf google protoc-gen-openapiv2 validate oryxa/events)

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
git clone --quiet "https://github.com/$REPO.git" "$TMP/src"
git -C "$TMP/src" checkout --quiet "$REV"
SHA="$(git -C "$TMP/src" rev-parse HEAD)"

rm -rf "$DEST"
mkdir -p "$DEST/crates" "$DEST/proto/oryxa" "$DEST/schema" "$DEST/policies"
for c in "${CRATES[@]}"; do cp -R "$TMP/src/crates/$c" "$DEST/crates/$c"; done
for p in "${PROTO[@]}"; do cp -R "$TMP/src/proto/$p" "$DEST/proto/$p"; done
cp "$TMP/src/proto/README.md" "$DEST/proto/README.md" 2>/dev/null || true
cp "$TMP/src/schema/"* "$DEST/schema/"
cp "$TMP/src/policies/"* "$DEST/policies/"

# A nested workspace so the crates inherit the platform's own package and dependency settings.
# The [patch] section is dropped: it only serves crates that are not vendored.
{
  echo "# Generated by scripts/sync-platform.sh from $REPO@$SHA. Do not edit."
  awk '/^\[patch/{skip=1} /^\[/{if($0 !~ /^\[patch/) skip=0} !skip' "$TMP/src/Cargo.toml" \
    | sed -E 's|^members = .*|members = ["crates/*"]|; /^exclude = /d'
} > "$DEST/Cargo.toml"

# The platform's lockfile, so the base builds and tests with the versions the platform pins.
# (A fresh resolve picks workos 3.5, which turns on a second jsonwebtoken crypto backend and panics.)
cp "$TMP/src/Cargo.lock" "$DEST/Cargo.lock"

echo "$SHA" > "$DEST/PLATFORM_REV"
echo "vendored $REPO@$SHA"
